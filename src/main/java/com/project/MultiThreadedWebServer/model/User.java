package com.project.MultiThreadedWebServer.model;

import com.fasterxml.jackson.annotation.JsonInclude;

/**
 * ╔══════════════════════════════════════════════════════════════════════════════╗
 * ║                              USER MODEL                                      ║
 * ║                    (Domain Object / Value Object / DTO)                      ║
 * ╚══════════════════════════════════════════════════════════════════════════════╝
 *
 * This class represents a User entity. In Spring Boot applications, you would
 * typically have model/entity classes like this to represent your data.
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * WHY USE A MODEL CLASS INSTEAD OF Map<String, Object>?
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * Using raw Maps:
 * ┌─────────────────────────────────────────────────────────────────────────────┐
 * │  Map<String, Object> user = new HashMap<>();                                │
 * │  user.put("name", "John");                                                  │
 * │  user.put("emil", "john@mail.com");  // ❌ Typo! No compiler error!        │
 * │  String name = (String) user.get("name");  // Ugly casting!               │
 * └─────────────────────────────────────────────────────────────────────────────┘
 *
 * Using a model class:
 * ┌─────────────────────────────────────────────────────────────────────────────┐
 * │  User user = new User(1L, "John", "john@mail.com", "USER", now, null);     │
 * │  user.emil();                    // ❌ Compiler error! Typo caught!        │
 * │  String name = user.name();      // Type-safe, no casting!                 │
 * └─────────────────────────────────────────────────────────────────────────────┘
 *
 * Benefits of model classes:
 *   1. Type Safety    → Compiler catches errors at build time
 *   2. IDE Support    → Auto-complete for field names
 *   3. Validation     → Can add @NotNull, @Email, etc.
 *   4. Documentation  → Fields are self-documenting
 *   5. Serialization  → Jackson automatically converts to/from JSON
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * WHY A RECORD (IMMUTABLE) INSTEAD OF A GETTER/SETTER POJO?
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * Once created, a User's fields never change. An "update" creates a NEW User
 * object (see withName / withEmail).
 *
 * Why immutability matters in a multi-threaded server:
 * many worker threads read users at the same time. If one thread mutated a
 * shared object while another was serializing it to JSON, the reader could
 * see half-updated data or crash with ConcurrentModificationException.
 * Immutable objects can be shared between threads with no locking at all.
 *
 * Jackson (2.12+) serializes records out of the box:
 *   {"id":1,"name":"John Doe","email":"john@example.com","role":"USER","createdAt":1700000000000}
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * IN SPRING BOOT WITH JPA
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * JPA entities can't be records (JPA needs a no-arg constructor and mutable
 * fields), so a real app would have a mutable @Entity class plus an
 * immutable DTO like this one for the API layer.
 *
 * @param id        Unique identifier, generated by the repository
 * @param name      Display name
 * @param email     Email address
 * @param role      Role, defaults to user.default-role from application.properties
 * @param createdAt Creation time (epoch millis)
 * @param updatedAt Last update time (epoch millis), null if never updated (omitted from JSON)
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
public record User(Long id, String name, String email, String role, long createdAt, Long updatedAt) {

    public User withName(String newName) {
        return new User(id, newName, email, role, createdAt, System.currentTimeMillis());
    }

    public User withEmail(String newEmail) {
        return new User(id, name, newEmail, role, createdAt, System.currentTimeMillis());
    }
}
