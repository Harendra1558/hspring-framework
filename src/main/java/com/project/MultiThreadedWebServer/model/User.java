package com.project.MultiThreadedWebServer.model;

import com.fasterxml.jackson.annotation.JsonInclude;

/**
 * The User domain object.
 *
 * It's a Java record, so it is IMMUTABLE: once created, its fields never change.
 * An "update" creates a NEW User object (see withName / withEmail).
 *
 * Why immutability matters in a multi-threaded server:
 * many worker threads read users at the same time. If one thread mutated a
 * shared object while another was serializing it to JSON, the reader could
 * see half-updated data or crash with ConcurrentModificationException.
 * Immutable objects can be shared between threads with no locking at all.
 *
 * Jackson (2.12+) serializes records out of the box:
 *   {"id":1,"name":"John Doe","email":"john@example.com","createdAt":1700000000000}
 *
 * @param id        Unique identifier, generated by the repository
 * @param name      Display name
 * @param email     Email address
 * @param createdAt Creation time (epoch millis)
 * @param updatedAt Last update time (epoch millis), null if never updated (omitted from JSON)
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
public record User(Long id, String name, String email, long createdAt, Long updatedAt) {

    public User withName(String newName) {
        return new User(id, newName, email, createdAt, System.currentTimeMillis());
    }

    public User withEmail(String newEmail) {
        return new User(id, name, newEmail, createdAt, System.currentTimeMillis());
    }
}
